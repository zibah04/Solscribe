    def adapt_layout(self):
        compact = self.width() < 1000 or self.height() < 640
        self.sidebar.setVisible(not compact)
        self.compact_toolbar.setVisible(compact)

    def resizeEvent(self, event):
        super().resizeEvent(event)
        if hasattr(self, 'sidebar') and hasattr(self, 'compact_toolbar'):
            self.adapt_layout()

    def focus_tab(self, index):
        self.tabs.setCurrentIndex(index)
        self.work_scroll.ensureWidgetVisible(self.tabs, 0, 0)

