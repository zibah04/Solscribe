class WindowLayout:
    @staticmethod
    def _label(text, role='Muted'):
        w = QLabel(text)
        w.setObjectName(role)
        return w

    @staticmethod
    def _button(text, role=None):
        w = QPushButton(text)
        if role:
            w.setObjectName(role)
        w.setCursor(Qt.PointingHandCursor)
        return w

